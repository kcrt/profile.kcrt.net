"""Build icons.svg (an SVG sprite) from the Font Awesome Free icons used in index.html.

Every `icons.svg#<name>` reference in index.html is looked up in the Font Awesome Free
solid / brands / regular sets and written out as a <symbol id="<name>">.

Usage: ./scripts/build_icons.py
"""

import re
import urllib.error
import urllib.request
from pathlib import Path

FONT_AWESOME_VERSION: str = "5.15.4"
ICON_SETS: tuple[str, ...] = ("solid", "brands", "regular")
SOURCE_URL: str = "https://cdn.jsdelivr.net/npm/@fortawesome/fontawesome-free@{version}/svgs/{icon_set}/{name}.svg"

ROOT_DIR: Path = Path(__file__).resolve().parent.parent
HTML_PATH: Path = ROOT_DIR / "index.html"
SPRITE_PATH: Path = ROOT_DIR / "icons.svg"

ICON_REFERENCE_PATTERN: re.Pattern[str] = re.compile(r"icons\.svg#([\w-]+)")
SVG_PATTERN: re.Pattern[str] = re.compile(r'<svg[^>]*viewBox="([^"]+)"[^>]*>(.*)</svg>', re.DOTALL)
COMMENT_PATTERN: re.Pattern[str] = re.compile(r"<!--.*?-->", re.DOTALL)


def find_icon_names(html: str) -> list[str]:
    return sorted(set(ICON_REFERENCE_PATTERN.findall(html)))


def fetch_icon_svg(name: str) -> str:
    for icon_set in ICON_SETS:
        url = SOURCE_URL.format(version=FONT_AWESOME_VERSION, icon_set=icon_set, name=name)
        try:
            with urllib.request.urlopen(url) as response:
                return response.read().decode("utf-8")
        except urllib.error.HTTPError as error:
            if error.code != 404:
                raise
    raise LookupError(f"Icon '{name}' not found in Font Awesome Free {FONT_AWESOME_VERSION}")


def to_symbol(name: str, svg: str) -> str:
    match = SVG_PATTERN.search(svg)
    if match is None:
        raise ValueError(f"Unexpected SVG format for icon '{name}'")
    view_box, body = match.groups()
    return f'\t<symbol id="{name}" viewBox="{view_box}">{COMMENT_PATTERN.sub("", body).strip()}</symbol>'


def build_sprite(names: list[str]) -> str:
    symbols = "\n".join(to_symbol(name, fetch_icon_svg(name)) for name in names)
    return (
        '<svg xmlns="http://www.w3.org/2000/svg">\n'
        f"\t<!-- Font Awesome Free {FONT_AWESOME_VERSION} by @fontawesome - https://fontawesome.com"
        " License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License) -->\n"
        "\t<!-- Generated by scripts/build_icons.py -->\n"
        f"{symbols}\n"
        "</svg>\n"
    )


def main() -> None:
    names = find_icon_names(HTML_PATH.read_text(encoding="utf-8"))
    SPRITE_PATH.write_text(build_sprite(names), encoding="utf-8")
    print(f"Wrote {len(names)} icons to {SPRITE_PATH.relative_to(ROOT_DIR)}: {', '.join(names)}")


if __name__ == "__main__":
    main()
